# -*- coding: utf-8 -*-
"""
猜成语（Guess Idiom by Clue）
=============================
看提示线索猜成语。内置常见成语及释义线索，答对得分。纯标准库实现。
运行：python3 2026-10-30_猜成语.py
"""

import random

CLUES = [
    ("画蛇添足", "在画好的蛇身上多添脚，比喻多此一举。"),
    ("守株待兔", "守着树桩等兔子来撞，比喻不努力想碰运气。"),
    ("亡羊补牢", "羊丢了才修补羊圈，比喻出了问题及时补救。"),
    ("井底之蛙", "井底的青蛙看天很小，比喻眼界狭窄。"),
    ("一鸣惊人", "平时不显山露水，一出手就让人刮目相看。"),
    ("胸有成竹", "画竹前心里已有竹子的样子，比喻事前有把握。"),
    ("对牛弹琴", "给牛弹琴它听不懂，比喻对不懂道理的人讲道理。"),
    ("狐假虎威", "狐狸借老虎的威风吓唬百兽，比喻借他人势力欺人。"),
    ("自相矛盾", "一个人卖矛又卖盾，说自己的矛刺穿一切盾，又说盾挡住一切矛。"),
    ("刻舟求剑", "剑掉水里在船上刻记号，船走剑不走，比喻拘泥不知变通。"),
    ("画龙点睛", "画好龙最后点上眼睛就飞了，比喻关键处一句点明。"),
    ("掩耳盗铃", "捂住自己的耳朵偷铃铛，以为自己听不见别人也听不见。"),
    ("塞翁失马", "丢了马却因祸得福，比喻坏事可能变成好事。"),
    ("滥竽充数", "不会吹竽的人混在乐队里充数，比喻没本事混在里面。"),
    ("叶公好龙", "叶公喜欢龙，真龙来了却吓跑，比喻嘴上喜欢实际害怕。"),
]


def main():
    print("=" * 40)
    print("        🀄 猜成语 Guess Idiom")
    print("=" * 40)
    print("根据提示线索猜成语（四字）。答对得分，答错给首字提示。q退出。")
    pool = CLUES[:]
    random.shuffle(pool)
    score = 0
    total = min(6, len(pool))

    for i in range(total):
        idiom, clue = pool[i]
        print(f"\n[第{i+1}/{total}题] 提示：{clue}")
        ans = input("猜成语：").strip()
        if ans.lower() in ("q", "quit", "exit"):
            print(f"你退出游戏。得分 {score}/{i}。")
            return
        if ans == idiom:
            print(f"✅ 正确！{idiom}")
            score += 1
        else:
            print(f"❌ 不对。首字是「{idiom[0]}」，共4字。")
            ans2 = input("再猜一次：").strip()
            if ans2 == idiom:
                print(f"✅ 这次对了！{idiom}")
                score += 1
            else:
                print(f"答案：{idiom}")
    print(f"\n🎉 游戏结束，得分 {score}/{total}")


if __name__ == "__main__":
    main()
