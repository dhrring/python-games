    total = 10
    picked = random.sample(PROVINCES, total)
    correct = 0
    done = 0
    for i, (prov, cap, abbr, hint) in enumerate(picked, 1):
        r = ask(prov, cap, abbr, hint, i, total)
        if r is None:
            print("提前结束。")
            break
        done = i
        if r:
            correct += 1

