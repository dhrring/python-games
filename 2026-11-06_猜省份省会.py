def ask(prov, cap, abbrev, hint, idx, total):
    print(f"\n第 {idx}/{total} 题：「{prov}」的省会是哪里？")
    for chance in range(1, 3):
        got = input(f"第{chance}次：").strip()
        if got.lower() in ("q", "quit", "exit"):
            return None
        got = got.replace("市", "").strip()
        if got == cap:
            print("✅ 答对了！")
            return True
        if chance == 1:
            print(f"提示：简称「{abbrev}」，{hint}。")
        else:
            print(f"❌ 答案是：{cap}（{prov}）")
    return False


